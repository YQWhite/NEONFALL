import assert from 'node:assert/strict';
import { AudioEngine } from '../src/engine/audio.ts';
import { MenuMusic } from '../src/ui/menu-music.ts';
import { buildNFM } from '../src/core/nfm.ts';

const gain = () => ({ gain: { value: 0, linearRampToValueAtTime(v) { this.value = v; }, cancelScheduledValues() {}, setValueAtTime(v) { this.value = v; } }, connect() {}, disconnect() {} });
const sources = [];
const ctx = { currentTime: 0, state: 'running', createGain: gain, createBufferSource() {
  const source = { connect() {}, disconnect() {}, start(when, offset) { this.when = when; this.offset = offset; }, stop() {} };
  sources.push(source); return source;
} };
const audio = new AudioEngine(); audio.ctx = ctx; audio.master = gain();
audio.decode = async () => ({ duration: 100 });
audio.setPreviewLooping(false);
await audio.previewMusic(new Uint8Array([1]), 'first', 30000, .5);
assert.equal(sources.at(-1).loop, false, 'playlist does not loop in the audio graph');
ctx.currentTime = 71;
assert.equal(audio.previewTimeSec, 100, 'ended playlist position stays at the end, never preview point');
assert.equal(audio.previewEnded, true);
ctx.currentTime = 95;
assert.equal(audio.previewTimeSec, 100, 'slow next-song load cannot replay the old preview');
audio.setPreviewLooping(true);
assert.equal(sources.at(-1).loop, true, 'song select restores single-song loop');
assert.equal(sources.at(-1).offset, 30, 'changing mode after EOF restarts the selected preview');
ctx.currentTime += 75;
assert.ok(audio.previewTimeSec >= 30 && audio.previewTimeSec < 100);
audio.setPreviewLooping(false);
const before = audio.previewTimeSec;
assert.ok(before >= 30 && before < 100, 'leaving single-loop mode preserves its current position');
audio.pausePreview(); ctx.currentTime += 200;
assert.equal(audio.previewTimeSec, before); assert.equal(audio.previewEnded, false);
audio.resumePreview(); assert.equal(sources.at(-1).loop, false);

const entries = ['Alpha', 'Beta'].map((title, i) => ({ id: `song${i}`, title, artist: 'Artist', creator: 'Mapper', version: 'Easy', stars: 1, keys: 4, addedAt: 10-i }));
audio.stopPreview();
const archive = entry => buildNFM({ format:'neonfall-chart', version:1, keys:4, timing:[{t:0,bpm:120}], sv:[], notes:[], meta:{title:entry.title,audio:'a.ogg',previewTime:30000} }, {'a.ogg':new Uint8Array([1,2,3])});
let releaseNext, reads = 0;
const slow = new Promise(resolve => { releaseNext = resolve; });
const app = { audio, settings:{musicVolume:.5}, store:{listCharts:async()=>entries,getChartBytes:async id=> {reads++; return id==='song1'?slow:archive(entries[0]);}}, w:1280,h:800 };
const music = new MenuMusic(app);
music.setScreen('menu');
await music.ensureStarted();
const waitFor = async predicate => { const until = Date.now()+3000; while(!predicate() && Date.now()<until) await new Promise(resolve=>setTimeout(resolve,5)); assert.ok(predicate()); };
await waitFor(()=>music.playingChart?.id==='song0');
ctx.currentTime += 94; music.update();
await waitFor(()=>reads===2);
assert.equal(music.playingChart.id,'song0','preloading next song does not interrupt current song');
ctx.currentTime += 12; music.update();
assert.equal(sources.at(-1).loop,false);
assert.equal(audio.previewTimeSec,100);
releaseNext(archive(entries[1]));
await waitFor(()=>music.playingChart?.id==='song1');
assert.equal(reads,2,'automatic advance reuses prepared archive instead of reading again');
assert.equal(sources.at(-1).offset,0,'playlist next song starts from beginning');
music.setScreen('select'); assert.equal(sources.at(-1).loop,true);
music.setScreen('settings'); assert.equal(sources.at(-1).loop,true,'submenu inherits selection loop policy');
music.setScreen('menu'); assert.equal(sources.at(-1).loop,false);
music.setScreen('play');
console.log('PASS natural playlist endings: no preview replay during slow load, next-song preparation reuse, pause/seek policy and submenu loop continuity');
