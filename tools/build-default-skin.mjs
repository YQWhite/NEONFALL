// Regenerate the bundled default from the user's original MSP, without changing
// any user library or executing the archive's Lua script.
import fs from 'node:fs';
import { importSkinArchive } from '../src/core/import.ts';
const root = new URL('../', import.meta.url);
const source = new URL('../RM_White_Blue_Bar_4-6K.msp', root);
const converted = importSkinArchive('RM_White_Blue_Bar_4-6K.msp', fs.readFileSync(source));
fs.mkdirSync(new URL('src/assets/', root), { recursive: true });
fs.writeFileSync(new URL('src/assets/default-msp.nfsk', root), converted.nfsk);
fs.writeFileSync(new URL('src/assets/default-msp-data.ts', root),
  '// Generated by tools/build-default-skin.mjs from RM White Blue Bar 4-6K by dreamcat.\n' +
  'export const defaultMspBase64 = ' + JSON.stringify(Buffer.from(converted.nfsk).toString('base64')) + ';\n');
const samples = new URL('../samples-converted/', root);
fs.mkdirSync(samples, { recursive: true });
fs.writeFileSync(new URL('RM White Blue Bar 4-6K.nfsk', samples), converted.nfsk);
console.log(`Bundled ${converted.name}: ${converted.nfsk.length} bytes, ${Object.keys(converted.skin.variants).join('/')}K`);
