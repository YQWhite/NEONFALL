// Regenerate the two embedded skin examples from the supplied original archives.
// Normal builds use the committed data modules and do not require these inputs.
// No user library is changed and no Lua scripts are executed.
import fs from 'node:fs';
import { isDeepStrictEqual } from 'node:util';
import { importSkinArchive } from '../src/core/import.ts';
import { readNFSK } from '../src/core/nfm.ts';
const root = new URL('../', import.meta.url);
const inputs = [
  { file: '----[Touhou project] .Remilia Scarlet. 2.0 ---- (月浊lpx).osk', credit: 'Remilia Scarlet 2.0 by 月浊lpx', stem: 'osu', symbol: 'defaultOsuBase64' },
  { file: 'RM_White_Blue_Bar_4-6K.msp', credit: 'RM White Blue Bar 4-6K by dreamcat', stem: 'msp', symbol: 'defaultMspBase64' },
];
const bundles = inputs.map(input => ({ ...input, converted: importSkinArchive(input.file, fs.readFileSync(new URL('../' + input.file, root))) }));
fs.mkdirSync(new URL('src/assets/', root), { recursive: true });
for (const { credit, stem, symbol, converted } of bundles) {
  const archivePath = new URL(`src/assets/default-${stem}.nfsk`, root);
  // ZIP timestamps alone must not churn megabytes of checked-in bundle data.
  const previous = fs.existsSync(archivePath) ? fs.readFileSync(archivePath) : null;
  const bytes = previous && isDeepStrictEqual(readNFSK(previous), readNFSK(converted.nfsk)) ? previous : converted.nfsk;
  fs.writeFileSync(archivePath, bytes);
  fs.writeFileSync(new URL(`src/assets/default-${stem}-data.ts`, root),
    `// Generated by tools/build-default-skin.mjs from ${credit}.\n` +
    `export const ${symbol} = ` + JSON.stringify(Buffer.from(bytes).toString('base64')) + ';\n');
  console.log(`Bundled ${converted.name}: ${converted.nfsk.length} bytes, ${Object.keys(converted.skin.variants).join('/')}K`);
}
