export function tr(source: string, values: Record<string, string | number> = {}): string {
  source = ({ NOFAIL: 'NO FAIL', FADEIN: 'FADE IN', DOWNSCROLL: 'DOWN SCROLL' } as Record<string, string>)[source] ?? source;
  const template = language === 'zh-CN' ? zh[source] ?? source : source;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? `{${key}}`));
}
